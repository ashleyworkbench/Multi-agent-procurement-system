-- -------------------------------------------------------
-- Table: purchase_orders
-- Generated by Agent 4 (Procurement Agent)
-- -------------------------------------------------------
CREATE TABLE IF NOT EXISTS purchase_orders (
    id                   SERIAL         PRIMARY KEY,
    po_number            VARCHAR(50)    NOT NULL UNIQUE,
    request_id           INTEGER        NOT NULL,   -- references ocr_procurement_db
    vendor_id            INTEGER        NOT NULL,
    vendor_name          VARCHAR(255)   NOT NULL,
    item_name            VARCHAR(255)   NOT NULL,
    quantity             INTEGER        NOT NULL,
    unit_price           NUMERIC(15, 2) NOT NULL,
    total_price          NUMERIC(15, 2) NOT NULL,
    currency             VARCHAR(10)    NOT NULL DEFAULT 'INR',
    status               VARCHAR(50)    NOT NULL DEFAULT 'PENDING_APPROVAL',
    -- status values: PENDING_APPROVAL | APPROVED | REJECTED | ORDERED | DELIVERED
    delivery_date_expected DATE,
    notes                TEXT,
    approval_tier        VARCHAR(50)    DEFAULT 'TIER_1_OFFICER',
    assigned_approver_name VARCHAR(255) DEFAULT 'Procurement Officer',
    assigned_approver_email VARCHAR(255) DEFAULT 'officer.procurement@procureflow.local',
    docusign_envelope_id VARCHAR(100),
    docusign_status      VARCHAR(50)    DEFAULT 'NOT_SENT',
    signed_document_url  TEXT,
    pdf_path             TEXT,
    created_at           TIMESTAMP      NOT NULL DEFAULT NOW(),
    updated_at           TIMESTAMP      NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_po_request_id  ON purchase_orders(request_id);
CREATE INDEX idx_po_vendor_id   ON purchase_orders(vendor_id);
CREATE INDEX idx_po_status      ON purchase_orders(status);
CREATE INDEX idx_po_number      ON purchase_orders(po_number);
CREATE INDEX idx_po_approval_tier ON purchase_orders(approval_tier);

-- -------------------------------------------------------
-- Table: procurement_audit
-- Immutable log of every status change on a purchase order
-- -------------------------------------------------------
CREATE TABLE IF NOT EXISTS procurement_audit (
    id          SERIAL       PRIMARY KEY,
    po_id       INTEGER      NOT NULL REFERENCES purchase_orders(id) ON DELETE CASCADE,
    po_number   VARCHAR(50)  NOT NULL,
    action      VARCHAR(100) NOT NULL,
    old_status  VARCHAR(50),
    new_status  VARCHAR(50),
    performed_by VARCHAR(100) NOT NULL DEFAULT 'system',
    notes       TEXT,
    created_at  TIMESTAMP    NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_audit_po_id ON procurement_audit(po_id);

-- -------------------------------------------------------
-- Table: procurement_events
-- Kafka event log — stores every event published by agents
-- -------------------------------------------------------
CREATE TABLE IF NOT EXISTS procurement_events (
    id           SERIAL        PRIMARY KEY,
    event_id     VARCHAR(100)  NOT NULL UNIQUE,
    event_type   VARCHAR(100)  NOT NULL,
    -- event types: OCR_REQUEST_CREATED | INVENTORY_EVALUATED |
    --              VENDOR_RECOMMENDED  | PURCHASE_ORDER_CREATED |
    --              APPROVAL_REQUESTED  | APPROVAL_GRANTED | APPROVAL_REJECTED
    topic        VARCHAR(100)  NOT NULL,
    payload      JSONB         NOT NULL,
    source_agent VARCHAR(100)  NOT NULL,
    created_at   TIMESTAMP     NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_events_event_type  ON procurement_events(event_type);
CREATE INDEX idx_events_source      ON procurement_events(source_agent);
CREATE INDEX idx_events_created_at  ON procurement_events(created_at);

-- -------------------------------------------------------
-- Auto-update trigger for purchase_orders.updated_at
-- -------------------------------------------------------
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_po_updated_at
    BEFORE UPDATE ON purchase_orders
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

