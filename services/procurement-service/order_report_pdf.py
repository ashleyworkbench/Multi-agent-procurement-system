from reportlab.pdfgen import canvas


class NumberedReportCanvas(canvas.Canvas):
    """
    Two-pass canvas for dynamic total page count,
    drawing professional running headers and footers.
    """
    def __init__(self, *args, **kwargs):
        super(NumberedReportCanvas, self).__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_decorations(num_pages)
            super(NumberedReportCanvas, self).showPage()
        super(NumberedReportCanvas, self).save()

    def draw_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#475569"))

        # Header on later pages
        if self._pageNumber > 1:
            self.drawString(40, 792 - 28, "ProcureFlow Enterprise — Purchase Order Lifecycle & Negotiation Dossier")
            self.setStrokeColor(colors.HexColor("#cbd5e1"))
            self.setLineWidth(0.5)
            self.line(40, 792 - 32, 612 - 40, 792 - 32)

        # Footer on all pages
        self.setStrokeColor(colors.HexColor("#cbd5e1"))
        self.setLineWidth(0.5)
        self.line(40, 36, 612 - 40, 36)
        
        self.drawString(40, 24, "CONFIDENTIAL & PROPRIETARY — GENERATED BY AGENT 6 (PROCUREFLOW INTELLIGENCE)")
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(612 - 40, 24, page_str)
        self.restoreState()


